"""Offline verification of LevelUpDiag campaign evidence (not a signature).

The campaign summary links each level report by exact relative path and SHA-256.
A verifier reconstructs the verdict from those reports.  To establish trust
across machines, pin the printed *summary* digest in an external evidence ledger.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from . import REPORT_SCHEMA, STANDARD, SUMMARY_SCHEMA, VERSION
from .verdicts import campaign_verdict, VERDICTS

INTEGRITY_FORMAT = 'levelupdiag.evidence-integrity.v1'
HEXDIGEST = re.compile(r'[0-9a-f]{64}\Z')
SAFE_ID = re.compile(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}\Z')
MAX_LEVELS = 128
MAX_SUMMARY_BYTES = 2 * 1024 * 1024
MAX_REPORT_BYTES = 16 * 1024 * 1024


class EvidenceError(ValueError):
    pass


def digest_file(path: Path, max_bytes: int) -> str:
    """Limit evidence sizes; do not hash a potentially unbounded external file."""
    h = hashlib.sha256()
    total = 0
    with path.open('rb') as file:
        while chunk := file.read(1024 * 1024):
            total += len(chunk)
            if total > max_bytes:
                raise EvidenceError(f'Evidence exceeds safe size: {path.name}')
            h.update(chunk)
    return h.hexdigest()


def _read_object(path: Path, max_bytes: int) -> dict:
    try:
        if path.is_symlink() or not path.is_file():
            raise EvidenceError(f'Missing or symlinked evidence: {path}')
        if path.stat().st_size > max_bytes:
            raise EvidenceError(f'Evidence exceeds safe size: {path.name}')
        with path.open('r', encoding='utf-8') as file:
            data = json.load(file)
        if not isinstance(data, dict):
            raise EvidenceError('Evidence JSON root must be an object')
        return data
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise EvidenceError(f'Unreadable evidence: {path.name}: {exc}') from exc


def canonical_level_result_path(level_id: str) -> str:
    """Emit portable, exact POSIX-style report paths on Linux and Windows.

    A path string serialized with native Windows separators is not a valid
    evidence manifest reference and must never be generated by the runner.
    """
    if not isinstance(level_id, str) or not SAFE_ID.fullmatch(level_id):
        raise EvidenceError('Invalid level ID for result path')
    return f'levels/{level_id}/result.json'


def _rows(summary: dict):
    expected = summary.get('expected_levels')
    levels = summary.get('levels')
    required = summary.get('required_levels')
    if not isinstance(expected, list) or not expected or len(expected) > MAX_LEVELS:
        raise EvidenceError('Missing or invalid expected_levels')
    if any(not isinstance(i, str) or not SAFE_ID.fullmatch(i) for i in expected) or len(set(expected)) != len(expected):
        raise EvidenceError('Invalid or duplicate level IDs')
    if (not isinstance(required, list) or any(not isinstance(i, str) for i in required)
            or len(set(required)) != len(required) or not set(required).issubset(set(expected))):
        raise EvidenceError('Invalid required_levels')
    if not isinstance(levels, list) or len(levels) != len(expected):
        raise EvidenceError('Missing, duplicate, or extra level results')
    for row, lid in zip(levels, expected):
        if not isinstance(row, dict) or row.get('id') != lid or not isinstance(row.get('name'), str):
            raise EvidenceError('Level order/identity does not match the campaign')
        if row.get('result') != canonical_level_result_path(lid):
            raise EvidenceError('Unsafe or noncanonical level result path')
        if row.get('verdict') not in VERDICTS:
            raise EvidenceError('Unknown level verdict')
    return levels, set(required)


def seal_campaign_evidence(run_root: Path, summary: dict) -> None:
    """Called only after final level results exist, before summary.json is written."""
    levels, _ = _rows(summary)
    files = {}
    for row in levels:
        rel = row['result']
        report = run_root / rel
        if report.is_symlink() or not report.is_file():
            raise EvidenceError(f'Missing level report: {rel}')
        files[rel] = digest_file(report, MAX_REPORT_BYTES)
    summary['evidence_integrity'] = {'format': INTEGRITY_FORMAT, 'algorithm': 'sha256', 'files': files}


def verify_campaign_evidence(summary_path: Path, expected_summary_sha256: str | None = None) -> tuple[dict, str]:
    """Verify hashes, complete level reports, verdict, target, and optional external anchor.

    No signature is verified here; rehashing a modified summary is not an attack
    barrier.  For independently pinned evidence, require expected_summary_sha256.
    """
    summary_path = Path(summary_path)
    if summary_path.name != 'summary.json':
        raise EvidenceError('Use the original runs/<run-id>/summary.json, not latest/')
    summary = _read_object(summary_path, MAX_SUMMARY_BYTES)
    sha = digest_file(summary_path, MAX_SUMMARY_BYTES)
    if expected_summary_sha256 is not None:
        if not isinstance(expected_summary_sha256, str) or not HEXDIGEST.fullmatch(expected_summary_sha256.lower()):
            raise EvidenceError('Invalid externally pinned summary SHA-256')
        if sha != expected_summary_sha256.lower():
            raise EvidenceError('Summary does not match external SHA-256 pin')
    if summary.get('schema') != SUMMARY_SCHEMA or summary.get('standard') != STANDARD or summary.get('standard_version') != VERSION:
        raise EvidenceError('Unsupported campaign summary schema/standard')
    run_id = summary.get('run_id')
    if not isinstance(run_id, str) or not SAFE_ID.fullmatch(run_id) or summary_path.parent.name != run_id:
        raise EvidenceError('Summary run_id does not match its run folder')
    target = summary.get('target_repo_root')
    if not isinstance(target, str) or not target or not isinstance(summary.get('selection'), str) or not summary['selection']:
        raise EvidenceError('Incomplete campaign context')
    rows, required = _rows(summary)
    integrity = summary.get('evidence_integrity')
    if not isinstance(integrity, dict) or integrity.get('format') != INTEGRITY_FORMAT or integrity.get('algorithm') != 'sha256':
        raise EvidenceError('Missing integrity manifest: older summaries are not qualified evidence')
    files = integrity.get('files')
    expected_paths = {r['result'] for r in rows}
    if not isinstance(files, dict) or set(files) != expected_paths:
        raise EvidenceError('Integrity manifest does not cover exactly the required reports')
    for digest in files.values():
        if not isinstance(digest, str) or not HEXDIGEST.fullmatch(digest):
            raise EvidenceError('Invalid SHA-256 in integrity manifest')
    results = []
    for row in rows:
        report_path = summary_path.parent / row['result']
        # Literal canonical path, no arbitrary report paths, and no symlink traversals.
        if report_path.parent.is_symlink() or report_path.parent.parent.is_symlink():
            raise EvidenceError('Symlinked report directory')
        if not report_path.resolve(strict=False).is_relative_to(summary_path.parent.resolve(strict=False)):
            raise EvidenceError('Evidence escapes the run directory')
        if report_path.is_symlink():
            raise EvidenceError('Symlinked level report')
        report_sha = digest_file(report_path, MAX_REPORT_BYTES)
        if report_sha != files[row['result']]:
            raise EvidenceError(f'Level evidence SHA-256 mismatch: {row["id"]}')
        report = _read_object(report_path, MAX_REPORT_BYTES)
        for field, expected_value in (
            ('schema', REPORT_SCHEMA), ('standard', STANDARD), ('standard_version', VERSION),
            ('run_id', run_id), ('level_id', row['id']), ('level_name', row['name']),
            ('target_repo_root', target), ('verdict', row['verdict']),
        ):
            if report.get(field) != expected_value:
                raise EvidenceError(f'Level {row["id"]}: mismatched {field}')
        if report.get('verdict') not in VERDICTS or not isinstance(report.get('findings'), list) or not isinstance(report.get('artifacts'), list):
            raise EvidenceError(f'Level {row["id"]}: invalid verdict/findings/artifacts')
        results.append(report)
    required_map = {lid: lid in required for lid in summary['expected_levels']}
    recomputed = campaign_verdict(results, required_map)
    protection = summary.get('target_protection')
    if protection is not None:
        if not isinstance(protection, dict) or protection.get('verdict') not in {'PASS','ERROR'}:
            raise EvidenceError('Invalid target_protection')
        if protection['verdict'] == 'ERROR':
            recomputed = 'ERROR'
    if summary.get('verdict') != recomputed:
        raise EvidenceError(f'Campaign verdict mismatch: recorded={summary.get("verdict")}, recalculated={recomputed}')
    counts = summary.get('counts')
    measured = {verdict: sum(r['verdict'] == verdict for r in results) for verdict in VERDICTS}
    if not isinstance(counts, dict) or set(counts) != set(measured) or any(type(counts[k]) is not int or counts[k] != v for k,v in measured.items()):
        raise EvidenceError('Campaign counts do not match level reports')
    return summary, sha
